"""Document exports (DOCX and PDF).

A report is first built as a list of simple blocks - heading, paragraph,
bullets, table, note - by one function per report type. The same block list
is then rendered either to DOCX (python-docx) or to PDF (PyMuPDF's HTML
"Story" layout engine). This keeps all 12 reports consistent in both formats.
"""
import html
import io
from datetime import datetime, timezone

import docx
import fitz
from docx.enum.section import WD_ORIENT
from docx.shared import Pt, RGBColor

REPORTS = {
    "srs": "Software Requirements Specification",
    "requirements": "Functional and Non-Functional Requirements",
    "user_stories": "User Stories and Acceptance Criteria",
    "use_cases": "Use-Case Descriptions",
    "quality": "Requirement Quality Analysis",
    "compliance": "Compliance Mapping Report",
    "security": "Security and Privacy Report",
    "risks": "Risk Register",
    "traceability": "Requirements Traceability Matrix",
    "sdlc": "SDLC Recommendation Report",
    "workflow": "SDLC Workflow",
    "consolidated": "Consolidated Project Analysis Report",
}


# --------------------------------------------------------------------------
# Block helpers
# --------------------------------------------------------------------------
def h(level: int, text: str) -> tuple:
    return ("h", level, text)


def p(text: str) -> tuple:
    return ("p", text)


def bullets(items: list[str]) -> tuple:
    return ("bullets", [str(i) for i in items if i])


def table(headers: list[str], rows: list[list]) -> tuple:
    return ("table", headers, [[_cell(c) for c in row] for row in rows])


def note(text: str) -> tuple:
    return ("note", text)


def _cell(value) -> str:
    if isinstance(value, list):
        return "; ".join(str(v) for v in value)
    if isinstance(value, float):
        return f"{value:.2f}"
    return "" if value is None else str(value)


# --------------------------------------------------------------------------
# Sections (shared by the individual reports and the consolidated report)
# --------------------------------------------------------------------------
def header_blocks(a: dict, title: str) -> list:
    pr = a["project"]
    mode = ("DEMONSTRATION MODE - generated by ReqPilot's rule-based agents only (no OpenAI model was used)."
            if a["mode"] == "demo" else f"Generated with OpenAI model {a['model_name']} combined with rule-based checks.")
    return [
        h(1, title),
        table(["Field", "Value"], [
            ["Project", pr["name"]], ["Domain", pr["domain_label"]], ["Jurisdiction", pr["jurisdiction"]],
            ["Scale", pr["scale"]], ["Budget", pr["budget"] or "not provided"],
            ["Schedule", pr["schedule"] or "not provided"], ["Analysis ID", a["id"]],
            ["Version", f"{a.get('version', 1)}" + (" (created by Stage 2 refinement)" if a.get("version", 1) > 1 else "")],
            ["Analysis status", a["status"]], ["Requirement baseline", a["baseline_status"]],
            ["Clarification", _clarification_line(a)],
            ["Generated", datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")]]),
        note(mode),
        note("AI-assisted analysis: all results require review and approval by authorised people. ReqPilot does "
             "not provide legal advice. 'Illustrative' sources are fictional demonstration policies; 'reference' "
             "sources are document-level summaries, not regulatory text."),
    ]


def _clarification_line(a: dict) -> str:
    c = a.get("clarification") or {}
    if not c.get("total") and not c.get("stage2_questions"):
        return "no clarification questions"
    return (f"{c.get('total', 0) + c.get('stage2_questions', 0)} question(s); "
            f"{c.get('answered', 0) + c.get('stage2_answered', 0)} answered, {c.get('deferred', 0)} deferred; "
            f"{c.get('issues_resolved', 0)} issue(s) resolved through clarification")


def summary_section(a: dict) -> list:
    m = a["metrics"]
    rows = [["Submitted statements", m.get("submitted")], ["Extracted requirements", m.get("extracted")],
            ["Functional / non-functional", f"{m.get('functional')} / {m.get('non_functional')}"],
            ["Quality issues", m.get("quality_issues")], ["Compliance mappings", m.get("compliance_mappings")],
            ["Compliance gaps", m.get("compliance_gaps")], ["High/critical risks", m.get("high_risks")],
            ["Recommended SDLC", m.get("recommended_sdlc")], ["Suitability score", m.get("sdlc_score")]]
    return [h(2, "Executive summary"), p(a["summary"]), table(["Metric", "Value"], rows),
            h(3, "Key findings"), bullets(a["key_findings"] or ["None"])]


def requirements_section(a: dict, kinds: tuple[str, ...], title: str) -> list:
    reqs = [r for r in a["requirements"] if r["kind"] in kinds]
    rows = [[r["req_id"], r["statement"], r["categories"], r["priority"], r["risk_level"], r["source"],
             f"{r['confidence']:.2f}", r["status"]] for r in reqs]
    return [h(2, f"{title} ({len(reqs)})"),
            table(["ID", "Requirement", "Categories", "Priority", "Risk", "Source", "Conf.", "Status"], rows)
            if rows else p("None.")]


def stories_section(a: dict) -> list:
    blocks = [h(2, "User stories and acceptance criteria")]
    for r in a["requirements"]:
        blocks += [h(3, f"{r['req_id']}: {r['statement']}"), p(r["user_story"]),
                   bullets([f"AC: {c}" for c in r["acceptance_criteria"]] +
                           [f"Test: {t}" for t in r["test_recommendations"]])]
    return blocks


def use_case_section(a: dict) -> list:
    blocks = [h(2, "Use-case descriptions")]
    for uc in a["use_cases"]:
        blocks += [h(3, f"{uc['id']} {uc['name']}"),
                   table(["Element", "Description"], [
                       ["Primary actor", uc["actor"]], ["Preconditions", uc["preconditions"]],
                       ["Main flow", [f"{i}. {s}" for i, s in enumerate(uc["main_flow"], 1)]],
                       ["Alternate flows", uc["alternate_flows"]], ["Postconditions", uc["postconditions"]],
                       ["Requirements", uc["requirement_ids"]]])]
    return blocks if a["use_cases"] else blocks + [p("No use cases generated.")]


def findings_table(findings: list[dict]) -> tuple:
    return table(["Type", "Severity", "Requirements", "Finding", "Suggested correction"],
                 [[f["issue_type"], f["severity"], f["requirement_ids"], f"{f['title']}. {f['explanation']}",
                   f["suggestion"]] for f in findings])


def quality_section(a: dict) -> list:
    issues = [f for f in a["findings"] if f["kind"] == "quality"]
    blocks = [h(2, f"Requirement quality analysis ({len(issues)} issues)")]
    for label, types in [("Ambiguity", ("ambiguity", "untestable")), ("Incompleteness", ("incompleteness",)),
                         ("Conflicts", ("conflict", "stakeholder_conflict")), ("Duplicates", ("duplicate",)),
                         ("Infeasibility", ("infeasibility",)),
                         ("Missing acceptance criteria", ("missing_acceptance_criteria",)),
                         ("Missing sources and undefined terms", ("missing_source", "undefined_term"))]:
        group = [f for f in issues if f["issue_type"] in types]
        if group:
            blocks += [h(3, f"{label} ({len(group)})"), findings_table(group)]
    return blocks


def open_issues_section(a: dict) -> list:
    questions = [f"{', '.join(f['requirement_ids']) or 'General'}: {f['question']}" for f in a["findings"] if f["question"]]
    assumptions = [f["title"] for f in a["findings"] if f["kind"] == "assumption"]
    review = [f["title"] for f in a["findings"] if f["kind"] in ("expert_review", "input_warning")]
    review += [f"{m['requirement_id']} -> {m['document_name']} {m['control_ref']}" for m in a["mappings"]
               if m["needs_verification"]][:30]
    return [h(2, "Open issues and assumptions"), h(3, "Questions for stakeholders"), bullets(questions or ["None"]),
            h(3, "Assumptions made during analysis"), bullets(assumptions or ["None"]),
            h(3, "Areas requiring expert review"), bullets(review or ["None"])]


def compliance_section(a: dict) -> list:
    rows = [[m["requirement_id"], f"{m['document_name']} - {m['control_ref']} {m['control_title']}",
             m["authenticity"], m["evidence_text"], "yes" if m["citation_verified"] else "NO",
             f"{m['confidence']:.2f}", "yes" if m["needs_verification"] else "no", m["status"]] for m in a["mappings"]]
    mapped = {m["requirement_id"] for m in a["mappings"]}
    unmapped = [r["req_id"] for r in a["requirements"]
                if r["req_id"] not in mapped and {"regulatory", "privacy", "security"} & set(r["categories"])]
    sources = [[s["name"], s["doc_type"], s["authenticity"], s["jurisdiction"], s["version"],
                len(s["mapped_requirements"])] for s in a["applicable_sources"]]
    gaps = [f for f in a["findings"] if f["kind"] == "compliance_gap"]
    return [h(2, "Compliance analysis"),
            note("Mappings are evidence-linked suggestions for a compliance officer, not legal determinations."),
            h(3, "Applicable sources"),
            table(["Document", "Type", "Authenticity", "Jurisdiction", "Version", "Mapped reqs"], sources)
            if sources else p("No knowledge-base sources matched."),
            h(3, f"Requirement-to-control mappings ({len(rows)})"),
            table(["Req", "Control", "Authenticity", "Evidence", "Citation verified", "Conf.", "Needs verification",
                   "Status"], rows) if rows else p("No mappings."),
            h(3, f"Compliance gaps ({len(gaps)})"), findings_table(gaps) if gaps else p("None."),
            h(3, "Regulatory/security/privacy requirements without a mapping"), p(", ".join(unmapped) or "None.")]


def security_section(a: dict) -> list:
    cov = [[c["label"], c["status"], c["requirement_ids"], c["safeguard"]] for c in a["security_coverage"]]
    sec_reqs = [[r["req_id"], r["statement"], r["priority"]] for r in a["requirements"] if "security" in r["categories"]]
    threats = [f for f in a["findings"] if f["kind"] == "threat"]
    privacy = [f for f in a["findings"] if f["kind"] == "privacy"]
    gaps = [f for f in a["findings"] if f["kind"] == "security_gap"]
    return [h(2, "Security and privacy analysis"), h(3, "Security coverage"),
            table(["Area", "Status", "Requirements", "Recommended safeguard"], cov),
            h(3, f"Identified security requirements ({len(sec_reqs)})"),
            table(["ID", "Requirement", "Priority"], sec_reqs) if sec_reqs else p("None."),
            h(3, f"Missing security controls ({len(gaps)})"), findings_table(gaps) if gaps else p("None."),
            h(3, f"Threats ({len(threats)})"),
            table(["STRIDE", "Severity", "Threat", "Requirements", "Safeguard"],
                  [[t["issue_type"], t["severity"], t["title"], t["requirement_ids"], t["suggestion"]] for t in threats]),
            h(3, f"Privacy considerations ({len(privacy)})"),
            table(["Consideration", "Requirements", "Recommendation"],
                  [[f["title"], f["requirement_ids"], f["suggestion"]] for f in privacy])]


def risk_section(a: dict) -> list:
    return [h(2, f"Risk register ({len(a['risks'])} risks)"),
            p("Score = likelihood (1-5) x impact (1-5). Severity: 1-4 Low, 5-9 Medium, 10-15 High, 16-25 Critical."),
            table(["ID", "Risk", "Category", "L", "I", "Score", "Severity", "Mitigation", "Requirements"],
                  [[r["risk_id"], r["description"], r["category"], r["likelihood"], r["impact"], r["score"],
                    r["severity"], r["mitigation"], r["requirement_ids"]] for r in a["risks"]])]


def traceability_section(a: dict) -> list:
    rows = [[t["requirement_id"], t["source_statement"], t["source"], t["regulatory_controls"], t["security_controls"],
             t["tests"], t["workflow_phases"], t["missing_links"] or "none", f"{t['coverage']:.0%}"]
            for t in a["traceability"]]
    coverage = a["metrics"].get("traceability_coverage", 0)
    return [h(2, "Requirements Traceability Matrix"), p(f"Average link coverage: {coverage:.0%}."),
            table(["Req", "Stakeholder statement", "Source", "Regulatory controls", "Security controls", "Tests",
                   "Workflow phases", "Missing links", "Coverage"], rows)]


def sdlc_section(a: dict) -> list:
    s = a["sdlc"]
    if not s:
        return [h(2, "SDLC recommendation"), p("No SDLC recommendation was produced (the SDLC agent failed).")]
    top = s["ranking"][0]
    blocks = [h(2, "SDLC recommendation"),
              p(f"Recommended model: {s['recommended_model']} - suitability {top['score']}/100. Status: {s['status']}"
                + (f" (approved model: {s['approved_model']})" if s["approved_model"] else "")),
              note("Suitability scores are not probabilities: they are the weighted percentage of each model's "
                   "preferences that this project's characteristics satisfy."),
              p(s["justification"])]
    if s["hybrid_explanation"]:
        blocks += [h(3, "Hybrid model composition"), p(s["hybrid_explanation"])]
    blocks += [h(3, "Ranking"),
               table(["Rank", "Model", "Score", "Base", "Rule penalties", "Strengths", "Weaknesses"],
                     [[r["rank"], r["model"], r["score"], r["base_score"],
                       [f"{x['rule']} {x['points']}" for x in r["penalties"]], r["strengths"], r["weaknesses"]]
                      for r in s["ranking"]]),
               h(3, "Decision factors"),
               table(["Factor", "Rating", "Rule rating", "Explanation", "LLM adjustment"],
                     [[f["name"], f["value"], f["rule_value"], f["explanation"],
                       f"{f['adjustment']:+d}: {f['llm_reason']}" if f["adjustment"] else ""] for f in s["factors"]]),
               h(3, "Decision rules applied"),
               bullets([f"{r['rule']}: {r['description']} -> penalties {r['penalties']}" for r in s["rules_applied"]]
                       or ["None"]),
               h(3, "Advantages"), bullets(top["advantages"]), h(3, "Disadvantages"), bullets(top["disadvantages"]),
               h(3, "Trade-offs"), bullets(s["trade_offs"])]
    return blocks


def workflow_section(a: dict) -> list:
    w = a["workflow"]
    if not w:
        return [h(2, "SDLC workflow"), p("No workflow was generated.")]
    blocks = [h(2, f"SDLC workflow - {w['sdlc_model']} (status: {w['status']})")]
    for ph in w["phases"]:
        blocks += [h(3, f"Phase {ph['order']}: {ph['name']}"), p(ph["description"]),
                   table(["Element", "Details"], [
                       ["Activities", ph["activities"]], ["Responsible roles", ph["roles"]],
                       ["Deliverables", ph["deliverables"]], ["Security checkpoints", ph["security"]],
                       ["Testing", ph["testing"]], ["Compliance checkpoints", ph["compliance"]],
                       ["Entry criteria", ph["entry_criteria"]], ["Exit criteria", ph["exit_criteria"]],
                       ["Approval gates", [f"{g['name']} ({', '.join(g['approvers'])})" for g in ph["approval_gates"]]
                        or "none"],
                       ["Traceability", ph["traceability"]], ["Key requirements", ph["key_requirements"]]]
                         + ([["Verifies", ph["verifies"]]] if ph.get("verifies") else []))]
    return blocks


def validation_section(a: dict) -> list:
    return [h(2, "Validation report"),
            table(["Check", "Status", "Detail"], [[c["check"], c["status"].upper(), c["detail"]]
                                                   for c in a["validation_report"]]),
            h(3, "Agent execution log"),
            table(["#", "Agent", "Status", "Mode", "ms", "Message"],
                  [[r["order"], r["agent"], r["status"], r["mode"], r["duration_ms"], r["message"]]
                   for r in a["agent_runs"]])]


def srs_section(a: dict) -> list:
    pr = a["project"]
    sources = sorted({r["source"] for r in a["requirements"]})
    return [h(2, "1. Introduction"),
            p(f"Purpose: this Software Requirements Specification describes the requirements for "
              f"'{pr['name']}', a {pr['domain_label']} application in the {pr['jurisdiction']} jurisdiction."),
            p(f"Scope: {pr['description'] or 'not provided.'}"),
            h(2, "2. Overall description"),
            p(f"Expected scale: {pr['scale']}. Budget: {pr['budget'] or 'not provided'}. "
              f"Schedule: {pr['schedule'] or 'not provided'}."),
            h(3, "Requirement sources (stakeholders and documents)"), bullets(sources),
            h(2, "3. Specific requirements")] + \
        requirements_section(a, ("functional",), "3.1 Functional requirements") + \
        requirements_section(a, ("business_rule",), "3.2 Business rules") + \
        requirements_section(a, ("non_functional",), "3.3 Non-functional requirements") + \
        requirements_section(a, ("constraint",), "3.4 Constraints") + \
        [h(2, "4. Use cases")] + use_case_section(a)[1:] + \
        [h(2, "5. Compliance considerations"),
         bullets([f"{s['name']} ({s['authenticity']}): requirements {', '.join(s['mapped_requirements'])}"
                  for s in a["applicable_sources"]] or ["No mapped sources."])] + open_issues_section(a)


BUILDERS = {
    "srs": srs_section,
    "requirements": lambda a: requirements_section(a, ("functional", "business_rule"), "Functional requirements")
    + requirements_section(a, ("non_functional", "constraint"), "Non-functional requirements and constraints"),
    "user_stories": stories_section,
    "use_cases": use_case_section,
    "quality": lambda a: quality_section(a) + open_issues_section(a),
    "compliance": compliance_section,
    "security": security_section,
    "risks": risk_section,
    "traceability": traceability_section,
    "sdlc": sdlc_section,
    "workflow": workflow_section,
    "consolidated": lambda a: summary_section(a) + requirements_section(a, ("functional", "business_rule"),
                                                                         "Functional requirements")
    + requirements_section(a, ("non_functional", "constraint"), "Non-functional requirements")
    + quality_section(a) + compliance_section(a) + security_section(a) + risk_section(a) + sdlc_section(a)
    + workflow_section(a) + traceability_section(a) + open_issues_section(a) + validation_section(a),
}


def build_report(kind: str, analysis: dict) -> list:
    return header_blocks(analysis, REPORTS[kind]) + BUILDERS[kind](analysis)


# --------------------------------------------------------------------------
# Renderers
# --------------------------------------------------------------------------
def render_docx(blocks: list) -> bytes:
    document = docx.Document()
    section = document.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = section.page_height, section.page_width
    document.styles["Normal"].font.name = "Calibri"
    document.styles["Normal"].font.size = Pt(10)
    for block in blocks:
        kind = block[0]
        if kind == "h":
            document.add_heading(block[2], level=block[1])
        elif kind == "p":
            document.add_paragraph(block[1])
        elif kind == "note":
            run = document.add_paragraph().add_run(block[1])
            run.italic, run.font.color.rgb = True, RGBColor(0x8A, 0x4B, 0x08)
        elif kind == "bullets":
            for item in block[1]:
                document.add_paragraph(item, style="List Bullet")
        elif kind == "table":
            headers, rows = block[1], block[2]
            tbl = document.add_table(rows=1, cols=len(headers))
            tbl.style = "Light Grid Accent 1"
            for cell, text in zip(tbl.rows[0].cells, headers):
                cell.text = text
            for row in rows:
                for cell, text in zip(tbl.add_row().cells, row):
                    cell.text = text
            for row in tbl.rows:
                for cell in row.cells:
                    for paragraph in cell.paragraphs:
                        for run in paragraph.runs:
                            run.font.size = Pt(8)
            document.add_paragraph()
    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


_PDF_CSS = """
body { font-family: sans-serif; font-size: 9px; color: #1e293b; }
h1 { font-size: 18px; color: #0f2a4a; margin-bottom: 6px; }
h2 { font-size: 13px; color: #0f2a4a; margin-top: 14px; border-bottom: 1px solid #cbd5e1; }
h3 { font-size: 10.5px; color: #1d4ed8; margin-top: 10px; }
p { margin: 4px 0; }
table { border-collapse: collapse; width: 100%; margin: 4px 0 8px 0; }
th { background-color: #e2e8f0; text-align: left; }
td, th { border: 1px solid #cbd5e1; padding: 2px 3px; font-size: 7.5px; vertical-align: top; }
.note { color: #8a4b08; font-style: italic; }
"""


def blocks_to_html(blocks: list) -> str:
    out = []
    esc = html.escape
    for block in blocks:
        kind = block[0]
        if kind == "h":
            out.append(f"<h{block[1]}>{esc(block[2])}</h{block[1]}>")
        elif kind == "p":
            out.append(f"<p>{esc(block[1])}</p>")
        elif kind == "note":
            out.append(f'<p class="note">{esc(block[1])}</p>')
        elif kind == "bullets":
            out.append("<ul>" + "".join(f"<li>{esc(i)}</li>" for i in block[1]) + "</ul>")
        elif kind == "table":
            head = "".join(f"<th>{esc(x)}</th>" for x in block[1])
            body = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in row) + "</tr>" for row in block[2])
            out.append(f"<table><tr>{head}</tr>{body}</table>")
    return "\n".join(out)


def render_pdf(blocks: list, footer: str) -> bytes:
    story = fitz.Story(html=blocks_to_html(blocks), user_css=_PDF_CSS)
    buffer = io.BytesIO()
    writer = fitz.DocumentWriter(buffer)
    page_rect = fitz.paper_rect("a4-l")
    content = page_rect + (36, 36, -36, -44)
    more = True
    while more:
        device = writer.begin_page(page_rect)
        more, _ = story.place(content)
        story.draw(device)
        writer.end_page()
    writer.close()
    # Add a footer with page numbers.
    pdf = fitz.open(stream=buffer.getvalue(), filetype="pdf")
    for number, page in enumerate(pdf, start=1):
        page.insert_text((36, page_rect.height - 20), f"{footer}  |  Page {number} of {pdf.page_count}",
                         fontsize=7, color=(0.4, 0.45, 0.5))
    return pdf.tobytes()


def export(kind: str, analysis: dict, fmt: str) -> tuple[bytes, str, str]:
    """Returns (content, media type, filename)."""
    blocks = build_report(kind, analysis)
    slug = "".join(ch if ch.isalnum() else "_" for ch in analysis["project"]["name"])[:40]
    filename = f"ReqPilot_{slug}_{kind}_A{analysis['id']}.{fmt}"
    if fmt == "docx":
        return (render_docx(blocks),
                "application/vnd.openxmlformats-officedocument.wordprocessingml.document", filename)
    footer = f"ReqPilot - {REPORTS[kind]} - {analysis['project']['name']} - analysis {analysis['id']}"
    return render_pdf(blocks, footer), "application/pdf", filename
